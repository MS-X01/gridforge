/* GridForge — export.js : sheet → CSV / TSV / JSON / JSONL / Markdown / SQL / HTML / XML / XLSX / project */
(function (root) {
  'use strict';
  const GF = (root.GF = root.GF || {});
  const u = GF.u;
  const io = (GF.io = GF.io || {});
  const str = (v) => (v == null ? '' : String(v));

  io.FORMATS = {
    csv: { ext: 'csv', mime: 'text/csv;charset=utf-8' },
    tsv: { ext: 'tsv', mime: 'text/tab-separated-values;charset=utf-8' },
    json: { ext: 'json', mime: 'application/json' },
    jsonl: { ext: 'jsonl', mime: 'application/x-ndjson' },
    md: { ext: 'md', mime: 'text/markdown' },
    sql: { ext: 'sql', mime: 'text/plain' },
    html: { ext: 'html', mime: 'text/html' },
    xml: { ext: 'xml', mime: 'application/xml' },
    xlsx: { ext: 'xlsx', mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' },
    gridforge: { ext: 'gridforge.json', mime: 'application/json' },
  };

  /** pick the columns/rows to export. o: {scope:'view'|'all', hidden:false, idx:[…] (view index)} */
  io.pick = (sh, o = {}) => {
    const ci = sh.cols.map((_, i) => i).filter((i) => o.hidden || !sh.cols[i].hidden);
    const rowIdx = o.scope === 'all' || !o.idx ? sh.rows.map((_, i) => i) : o.idx;
    return { cols: ci.map((i) => sh.cols[i]), heads: ci.map((i) => sh.cols[i].name), rows: rowIdx.map((i) => ci.map((c) => str(sh.rows[i][c]))) };
  };

  const csvCell = (v, d) => (/[",\r\n]/.test(v) || v.includes(d) || /^\s|\s$/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v);
  const sqlId = (s) => '"' + String(s).replace(/"/g, '""') + '"';
  const xmlTag = (s) => { let t = String(s).trim().replace(/[^\p{L}\p{N}_.-]+/gu, '_'); if (!/^[\p{L}_]/u.test(t)) t = '_' + t; return t; };
  const jsonVal = (col, v) => {
    if (v === '') return null;
    if (col.type === 'number' && u.isNum(v)) return u.num(v);
    if (col.type === 'boolean' && u.isBool(v)) return u.boolVal(v);
    return v;
  };

  /** build text for a format. o: {delim, bom, header, table, rtl, title} + pick options */
  io.build = (fmt, sh, o = {}) => {
    const { cols, heads, rows } = io.pick(sh, o);
    const header = o.header !== false;
    switch (fmt) {
      case 'csv': case 'tsv': {
        const d = fmt === 'tsv' ? '\t' : o.delim || ',';
        const all = header ? [heads, ...rows] : rows;
        return (o.bom === false ? '' : '\uFEFF') + all.map((r) => r.map((v) => csvCell(v, d)).join(d)).join('\r\n') + '\r\n';
      }
      case 'json':
        return JSON.stringify(rows.map((r) => Object.fromEntries(heads.map((h, i) => [h, jsonVal(cols[i], r[i])]))), null, 2);
      case 'jsonl':
        return rows.map((r) => JSON.stringify(Object.fromEntries(heads.map((h, i) => [h, jsonVal(cols[i], r[i])])))).join('\n') + '\n';
      case 'md': {
        const e = (v) => v.replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
        return [`| ${heads.map(e).join(' | ')} |`, `| ${heads.map((h, i) => (cols[i].type === 'number' ? '---:' : '---')).join(' | ')} |`, ...rows.map((r) => `| ${r.map(e).join(' | ')} |`)].join('\n') + '\n';
      }
      case 'sql': {
        const t = sqlId(o.table || u.slug(sh.name).replace(/-/g, '_').toLowerCase());
        const type = (c) => (c.type === 'number' ? 'NUMERIC' : c.type === 'date' ? 'DATE' : c.type === 'boolean' ? 'BOOLEAN' : 'TEXT');
        const lit = (c, v) => (v === '' ? 'NULL' : c.type === 'number' && u.isNum(v) ? String(u.num(v)) : c.type === 'boolean' && u.isBool(v) ? (u.boolVal(v) ? 'TRUE' : 'FALSE') : "'" + v.replace(/'/g, "''") + "'");
        const out = [`-- Generated by GridForge`, `CREATE TABLE ${t} (`, cols.map((c) => `  ${sqlId(c.name)} ${type(c)}${c.required ? ' NOT NULL' : ''}`).join(',\n'), `);`, ''];
        for (let i = 0; i < rows.length; i += 500) {
          out.push(`INSERT INTO ${t} (${heads.map(sqlId).join(', ')}) VALUES`);
          out.push(rows.slice(i, i + 500).map((r) => '  (' + r.map((v, k) => lit(cols[k], v)).join(', ') + ')').join(',\n') + ';');
        }
        return out.join('\n') + '\n';
      }
      case 'xml': {
        const row = xmlTag(o.row || 'row');
        return `<?xml version="1.0" encoding="UTF-8"?>\n<${xmlTag(sh.name)}>\n` + rows.map((r) => `  <${row}>\n` + heads.map((h, i) => `    <${xmlTag(h)}>${u.esc(r[i])}</${xmlTag(h)}>`).join('\n') + `\n  </${row}>`).join('\n') + `\n</${xmlTag(sh.name)}>\n`;
      }
      case 'html': {
        const dir = o.rtl ? 'rtl' : 'ltr';
        return `<!DOCTYPE html>\n<html lang="${o.rtl ? 'fa' : 'en'}" dir="${dir}"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">\n<title>${u.esc(o.title || sh.name)}</title>\n<style>body{font-family:system-ui,'Vazirmatn',sans-serif;margin:2rem;background:#f6f8fc;color:#1b2140}table{border-collapse:collapse;width:100%;background:#fff;box-shadow:0 2px 12px #0001;border-radius:8px;overflow:hidden}th{background:#2b3a8c;color:#fff;text-align:start;padding:.6rem .8rem;font-size:.85rem}td{padding:.5rem .8rem;border-bottom:1px solid #e4e9f5;font-size:.85rem}tr:nth-child(even) td{background:#f5f7fd}</style></head><body>\n<h2>${u.esc(o.title || sh.name)}</h2>\n<table><thead><tr>${heads.map((h) => `<th>${u.esc(h)}</th>`).join('')}</tr></thead><tbody>\n${rows.map((r) => `<tr>${r.map((v) => `<td>${u.esc(v)}</td>`).join('')}</tr>`).join('\n')}\n</tbody></table>\n<p style="opacity:.5;font-size:.75rem">Exported with GridForge</p></body></html>\n`;
      }
      default: throw new Error('Unknown format: ' + fmt);
    }
  };

  /** XLSX workbook bytes (all sheets or just `sh`) */
  io.buildXlsx = (sheets, o = {}) => {
    if (typeof XLSX === 'undefined') throw new Error('Excel library missing');
    const wb = XLSX.utils.book_new();
    const used = [];
    sheets.forEach((sh) => {
      const { cols, heads, rows } = io.pick(sh, o.sheetOpts && o.sheetOpts(sh) || o);
      const aoa = [heads, ...rows.map((r) => r.map((v, i) => (cols[i].type === 'number' && u.isNum(v) ? u.num(v) : cols[i].type === 'boolean' && u.isBool(v) ? u.boolVal(v) : v)))];
      const ws = XLSX.utils.aoa_to_sheet(aoa);
      ws['!cols'] = heads.map((h, ci) => ({ wch: Math.min(60, Math.max(8, h.length + 2, ...rows.slice(0, 500).map((r) => str(r[ci]).length + 2))) }));
      if (aoa.length > 1) ws['!autofilter'] = { ref: XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: aoa.length - 1, c: heads.length - 1 } }) };
      const name = u.uniqueName(sh.name.replace(/[\\/?*[\]:]/g, ' ').slice(0, 31) || 'Sheet', used);
      used.push(name);
      XLSX.utils.book_append_sheet(wb, ws, name);
    });
    return XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
  };
})(typeof window !== 'undefined' ? window : globalThis);
